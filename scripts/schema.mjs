// `npm run schema`: db/migrations/*.sql (SQLite-flavoured source of truth) → db/migrations.ts with a SQLite AND a Postgres version
// of every migration. Inlined so serverless bundles need no fs read. The Postgres translation is deliberately small and explicit:
//   id INTEGER PRIMARY KEY      → identity column (the app inserts explicit ids in seeds; server/db.ts syncIds() moves the sequence)
//   DEFAULT (datetime('now'))   → same 'YYYY-MM-DD HH:MM:SS' UTC text, so JSON output is identical on both databases
//   ms timestamps INTEGER       → BIGINT (Date.now() does not fit a 32-bit INTEGER)
//   TEXT                        → TEXT COLLATE "C" (byte order, like SQLite), so ORDER BY results match on any server locale
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
export const toPgDdl = s => s
  .replace(/\bid INTEGER PRIMARY KEY\b/g, 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/DEFAULT \(datetime\('now'\)\)/g, `DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))`)
  .replace(/\b(expires_at|created_at|last_seen|at) INTEGER\b/g, '$1 BIGINT')
  .replace(/\bTEXT\b/g, 'TEXT COLLATE "C"');
const dir = new URL('../db/migrations/', import.meta.url);
const list = readdirSync(dir).filter(f => /^\d{4}_.+\.sql$/.test(f)).sort()
  .map(f => { const sqlite = readFileSync(new URL(f, dir), 'utf8'); return { id: f.replace(/\.sql$/, ''), sqlite, pg: toPgDdl(sqlite) }; });
writeFileSync(new URL('../db/migrations.ts', import.meta.url),
  '// Generated from db/migrations/*.sql by `npm run schema` (scripts/schema.mjs). Do not edit by hand.\n' +
  'export type Migration = { id: string; sqlite: string; pg: string };\nexport const MIGRATIONS: Migration[] = ' + JSON.stringify(list, null, 1) + ';\n');
console.log(`db/migrations.ts: ${list.map(m => m.id).join(', ')}`);
